    APPOINTMENT_CREATED("Appointment Scheduled"),
    APPOINTMENT_CANCELLED("Appointment Cancelled"),
    APPOINTMENT_CHECKED_IN("Appointment Checked In"),
    QUEUE_TICKET_ISSUED("Queue Ticket Generated"),
    QUEUE_PATIENT_CALLED("Patient Called in Queue"),
