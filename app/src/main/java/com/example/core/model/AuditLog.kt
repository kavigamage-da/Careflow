data class AuditLog(
    val id: String,
    val timestamp: Long,
    val userId: String?,
    val username: String?,
    val userRole: UserRole?,
    val action: AuditAction,
    val entityName: String,
    val entityId: String?,
    val details: String,
    val ipOrDevice: String,
    val result: String // "SUCCESS", "FAILURE", "BLOCKED"
)
